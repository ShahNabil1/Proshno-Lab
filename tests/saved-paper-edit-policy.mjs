import {PGlite} from '@electric-sql/pglite';
import {readFile} from 'node:fs/promises';
const db=new PGlite();
await db.exec(`CREATE ROLE authenticated; CREATE SCHEMA auth;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$select current_setting('test.uid')::uuid$$;
GRANT USAGE ON SCHEMA auth TO authenticated;
CREATE TABLE saved_papers(id integer primary key,teacher_id uuid,settings jsonb);
ALTER TABLE saved_papers ENABLE ROW LEVEL SECURITY;
CREATE POLICY own_read ON saved_papers FOR SELECT TO authenticated USING(auth.uid()=teacher_id);
GRANT SELECT,UPDATE ON saved_papers TO authenticated;
INSERT INTO saved_papers VALUES(1,'11111111-1111-4111-8111-111111111111','{}'),(2,'22222222-2222-4222-8222-222222222222','{}');`);
await db.exec(await readFile(new URL('../supabase/migrations/20261020162530_saved_paper_edit_persistence.sql',import.meta.url),'utf8'));
await db.exec(`SELECT set_config('test.uid','11111111-1111-4111-8111-111111111111',false);SET ROLE authenticated;`);
assert.equal((await db.query(`UPDATE saved_papers SET settings='{"inlineEdits":{"question":"edited"}}' WHERE id=1 RETURNING id`)).rows.length,1);
assert.equal((await db.query(`SELECT settings->'inlineEdits'->>'question' edited FROM saved_papers WHERE id=1`)).rows[0].edited,'edited');
