
-- Create purchase_requests table
CREATE TABLE public.purchase_requests (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id uuid REFERENCES public.teachers(id) ON DELETE CASCADE,
  teacher_name text NOT NULL DEFAULT '',
  teacher_email text NOT NULL DEFAULT '',
  teacher_phone text NOT NULL DEFAULT '',
  institute_name text NOT NULL DEFAULT '',
  package_name text NOT NULL DEFAULT '',
  package_classes text NOT NULL DEFAULT '',
  package_price integer NOT NULL DEFAULT 0,
  coupon_code text DEFAULT '',
  discount integer NOT NULL DEFAULT 0,
  total_price integer NOT NULL DEFAULT 0,
  payment_method text NOT NULL DEFAULT '',
  transaction_id text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'pending',
  admin_note text DEFAULT '',
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  reviewed_at timestamp with time zone
);

-- Enable RLS
ALTER TABLE public.purchase_requests ENABLE ROW LEVEL SECURITY;

-- Teachers can read their own requests
CREATE POLICY "Teachers can read own purchase requests"
  ON public.purchase_requests FOR SELECT
  USING (auth.uid() = teacher_id);

-- Teachers can insert purchase requests
CREATE POLICY "Teachers can insert purchase requests"
  ON public.purchase_requests FOR INSERT
  WITH CHECK (auth.uid() = teacher_id);

-- Allow anonymous inserts for non-logged-in users
CREATE POLICY "Anon can insert purchase requests"
  ON public.purchase_requests FOR INSERT
  TO anon
  WITH CHECK (teacher_id IS NULL);

-- Admins can manage all
CREATE POLICY "Admins can manage all purchase requests"
  ON public.purchase_requests FOR ALL
  USING (has_role(auth.uid(), 'admin'::app_role));
