
-- Create coupons table
CREATE TABLE public.coupons (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  discount_type text NOT NULL DEFAULT 'fixed', -- 'fixed' or 'percentage'
  discount_value integer NOT NULL DEFAULT 0,
  max_discount integer DEFAULT NULL, -- cap for percentage discounts
  min_purchase integer NOT NULL DEFAULT 0,
  use_limit integer DEFAULT NULL, -- NULL = unlimited
  used_count integer NOT NULL DEFAULT 0,
  applicable_packages text[] DEFAULT NULL, -- NULL = all packages, or specific package identifiers
  is_active boolean NOT NULL DEFAULT true,
  expires_at timestamp with time zone DEFAULT NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now()
);

-- Enable RLS
ALTER TABLE public.coupons ENABLE ROW LEVEL SECURITY;

-- Everyone can read active coupons (needed for checkout validation)
CREATE POLICY "Anyone can read active coupons"
  ON public.coupons FOR SELECT
  USING (true);

-- Only admins can manage
CREATE POLICY "Admins can manage coupons"
  ON public.coupons FOR ALL
  USING (has_role(auth.uid(), 'admin'::app_role));
