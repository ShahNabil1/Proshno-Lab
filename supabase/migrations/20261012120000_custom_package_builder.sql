CREATE FUNCTION public.validate_custom_pricing() RETURNS trigger LANGUAGE plpgsql SET search_path=public AS $$
DECLARE entry record; owner_name text; package_name text;
BEGIN
  SELECT name INTO owner_name FROM public.classes WHERE id=NEW.class_id;
  SELECT class_name INTO package_name FROM public.pricing_packages WHERE id=NEW.all_package_id;
  IF btrim(public.normalize_subscription_text(package_name)) IS DISTINCT FROM btrim(public.normalize_subscription_text(owner_name)) THEN RAISE EXCEPTION 'All Subjects package must belong to the exact class'; END IF;
  IF (owner_name ~* '(english|eglish|ইংলিশ)') <> (NEW.version='english') THEN RAISE EXCEPTION 'Version does not match class'; END IF;
  IF (package_name ~* '(english|eglish|ইংলিশ)') <> (NEW.version='english') THEN RAISE EXCEPTION 'Package version does not match class'; END IF;
  IF jsonb_typeof(NEW.caps)<>'object' THEN RAISE EXCEPTION 'Caps must be an object'; END IF;
  FOR entry IN SELECT * FROM jsonb_each_text(NEW.caps) LOOP
    IF entry.key !~ '^[2-9][0-9]*$' AND entry.key !~ '^1[0-9]+$' THEN RAISE EXCEPTION 'Invalid cap subject count'; END IF;
    IF entry.value !~ '^[0-9]+(\.[0-9]{1,2})?$' OR entry.value::numeric <= 0 THEN RAISE EXCEPTION 'Invalid cap price'; END IF;
  END LOOP;
  RETURN NEW;
END $$;
CREATE TRIGGER validate_custom_pricing BEFORE INSERT OR UPDATE ON public.custom_package_pricing FOR EACH ROW EXECUTE FUNCTION public.validate_custom_pricing();

