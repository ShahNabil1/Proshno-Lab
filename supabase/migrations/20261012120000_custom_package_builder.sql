CREATE FUNCTION public.custom_package_catalog() RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
  SELECT coalesce(jsonb_agg(to_jsonb(catalog) ORDER BY sort_order,class_id),'[]'::jsonb) FROM (
    SELECT cp.*,c.name,p.price AS all_price,
      coalesce((SELECT jsonb_agg(jsonb_build_object(
        'subject_id',s.id,'class_id',s.class_id,'name',s.name,
        'individual_price',sp.individual_price,'is_special',coalesce(sp.is_special,false),
        'price',coalesce(sp.individual_price,CASE WHEN sp.is_special THEN cp.special_price ELSE cp.normal_price END),
        'groups',coalesce(sp.groups,'{}'::text[]),'is_active',coalesce(sp.is_active,true),'sort_order',coalesce(sp.sort_order,0)
      ) ORDER BY coalesce(sp.sort_order,0),s.id)
      FROM public.subjects s LEFT JOIN public.custom_package_subjects sp ON sp.subject_id=s.id
      WHERE s.class_id=cp.class_id AND coalesce(sp.is_active,true)), '[]'::jsonb) AS subjects
    FROM public.custom_package_pricing cp JOIN public.classes c ON c.id=cp.class_id
    JOIN public.pricing_packages p ON p.id=cp.all_package_id
    WHERE cp.is_active AND p.is_active AND NOT coalesce(p.is_coming_soon,false)
      AND p.subject_name='সকল বিষয়' AND p.subject_ids IS NULL
  ) catalog;
$$;
GRANT EXECUTE ON FUNCTION public.custom_package_catalog() TO anon,authenticated,service_role;

-- The single authoritative pricing engine. The browser receives quotes from
-- this function, and payment initiation calls it again with the authenticated user.
CREATE FUNCTION public.quote_custom_package(selection jsonb, buyer uuid DEFAULT auth.uid()) RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=public AS $$
DECLARE cp public.custom_package_pricing; p public.pricing_packages; ids bigint[];
  grp text := nullif(selection->>'group',''); total numeric:=0; cap numeric; price numeric;
  labels text; owned bigint[]; n integer; available integer;
BEGIN
  IF buyer IS DISTINCT FROM auth.uid() AND coalesce(auth.role(),'')<>'service_role' THEN RAISE EXCEPTION 'Forbidden'; END IF;
  IF jsonb_typeof(selection->'subject_ids') IS DISTINCT FROM 'array' THEN RAISE EXCEPTION 'Select subjects'; END IF;
  IF jsonb_array_length(selection->'subject_ids') NOT BETWEEN 1 AND 100 THEN RAISE EXCEPTION 'Select 1 to 100 subjects'; END IF;
  SELECT array_agg(value::bigint ORDER BY value::bigint) INTO ids FROM jsonb_array_elements_text(selection->'subject_ids');
  IF cardinality(ids)<>(SELECT count(DISTINCT x) FROM unnest(ids) x) THEN RAISE EXCEPTION 'Duplicate subjects'; END IF;
  SELECT * INTO cp FROM public.custom_package_pricing WHERE class_id=(selection->>'class_id')::bigint AND version=selection->>'version' AND is_active;
  IF NOT FOUND THEN RAISE EXCEPTION 'Class or version unavailable'; END IF;
  IF cardinality(cp.groups)>0 AND (grp IS NULL OR NOT grp=ANY(cp.groups)) THEN RAISE EXCEPTION 'Choose a valid group'; END IF;
  IF cardinality(cp.groups)=0 AND grp IS NOT NULL THEN RAISE EXCEPTION 'This class has no groups'; END IF;
  SELECT * INTO p FROM public.pricing_packages WHERE id=cp.all_package_id AND is_active AND NOT coalesce(is_coming_soon,false) AND subject_name='সকল বিষয়' AND subject_ids IS NULL;
  IF NOT FOUND OR p.price<=0 THEN RAISE EXCEPTION 'All Subjects package unavailable'; END IF;
  SELECT count(*),sum(coalesce(sp.individual_price,CASE WHEN sp.is_special THEN cp.special_price ELSE cp.normal_price END)),string_agg(s.name,', ' ORDER BY s.id)
    INTO available,total,labels FROM public.subjects s LEFT JOIN public.custom_package_subjects sp ON sp.subject_id=s.id
    WHERE s.id=ANY(ids) AND s.class_id=cp.class_id AND coalesce(sp.is_active,true)
      AND (coalesce(cardinality(sp.groups),0)=0 OR grp=ANY(sp.groups));
  IF available<>cardinality(ids) THEN RAISE EXCEPTION 'Subject does not belong to selected class, version or group'; END IF;
  n:=cardinality(ids);
  -- Largest configured tier also applies to larger selections. For 6–8, 5+
  -- compares the actual total directly to All Subjects instead of reusing tier 4.
  SELECT value::numeric INTO cap FROM jsonb_each_text(cp.caps)
    WHERE key::integer=n OR (cp.class_level NOT IN ('6','7','8') AND key::integer<=n)
    ORDER BY key::integer DESC LIMIT 1;
  price:=least(total,coalesce(cap,total),p.price);
  SELECT coalesce(array_agg(x),'{}'::bigint[]) INTO owned FROM unnest(ids) x
    WHERE buyer IS NOT NULL AND (
      EXISTS(SELECT 1 FROM public.user_permissions up WHERE up.user_id=buyer AND up.class_id=cp.class_id AND up.subject_id=x)
      OR EXISTS(SELECT 1 FROM public.custom_package_purchases pu JOIN public.subscriptions sub ON sub.id=pu.subscription_id
        WHERE pu.user_id=buyer AND pu.class_id=cp.class_id AND pu.version=cp.version AND x=ANY(pu.subject_ids)
          AND sub.status='active' AND sub.starts_at<=now() AND sub.ends_at>now())
      OR EXISTS(SELECT 1 FROM public.subscriptions sub JOIN public.subjects s ON s.id=x JOIN public.classes c ON c.id=s.class_id
        WHERE sub.teacher_id=buyer AND sub.package_type='fixed' AND sub.status='active'
          AND (sub.starts_at IS NULL OR sub.starts_at<=now()) AND (sub.ends_at IS NULL OR sub.ends_at>now())
          AND public.plan_covers_selection(sub.plan,c.name,s.name)));
  RETURN jsonb_build_object('kind','custom','version',cp.version,'class_id',cp.class_id,'class_level',cp.class_level,
    'group',grp,'subject_ids',ids,'class_name',p.class_name,'subject_name',labels,'duration_days',365,
    'regular_total',total,'price',price,'savings',greatest(0,total-price),'all_price',p.price,
    'all_package_id',p.id,'upgrade_difference',greatest(0,p.price-price),'owned_subject_ids',owned);
END $$;
REVOKE ALL ON FUNCTION public.quote_custom_package(jsonb,uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.quote_custom_package(jsonb,uuid) TO anon,authenticated,service_role;

-- Preserve fixed-plan matching while separating custom entitlements from labels.
CREATE OR REPLACE FUNCTION public.can_read_question(_class_id bigint,_subject_id bigint) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
 SELECT EXISTS(SELECT 1 FROM public.subjects WHERE id=_subject_id AND class_id=_class_id) AND (
   public.has_role(auth.uid(),'admin') OR public.has_role(auth.uid(),'developer')
   OR EXISTS(SELECT 1 FROM public.user_permissions WHERE user_id=auth.uid() AND class_id=_class_id AND subject_id=_subject_id)
   OR EXISTS(SELECT 1 FROM public.custom_package_purchases pu JOIN public.subscriptions sub ON sub.id=pu.subscription_id
     WHERE pu.user_id=auth.uid() AND pu.class_id=_class_id AND _subject_id=ANY(pu.subject_ids)
       AND sub.status='active' AND sub.starts_at<=now() AND sub.ends_at>now())
   OR EXISTS(SELECT 1 FROM public.subscriptions sub JOIN public.classes c ON c.id=_class_id JOIN public.subjects s ON s.id=_subject_id
     WHERE sub.teacher_id=auth.uid() AND sub.package_type='fixed' AND sub.status='active'
       AND (sub.starts_at IS NULL OR sub.starts_at<=now()) AND (sub.ends_at IS NULL OR sub.ends_at>now())
       AND public.plan_covers_selection(sub.plan,c.name,s.name)));
$$;

CREATE FUNCTION public.custom_package_owned_subjects(selected_class bigint) RETURNS bigint[]
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
 SELECT coalesce(array_agg(s.id),'{}'::bigint[]) FROM public.subjects s
 WHERE s.class_id=selected_class AND auth.uid() IS NOT NULL AND public.can_read_question(s.class_id,s.id);
$$;
REVOKE ALL ON FUNCTION public.custom_package_owned_subjects(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.custom_package_owned_subjects(bigint) TO authenticated;

-- Persist custom orders before contacting bKash. Serializing preparation per
-- buyer prevents two tabs from opening payments for overlapping subjects.
CREATE FUNCTION public.reserve_custom_payment(context jsonb) RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE buyer uuid:=(context->>'user_id')::uuid; item jsonb:=context->'selected_packages'->0; id bigint; fresh jsonb;
BEGIN
 PERFORM pg_advisory_xact_lock(hashtextextended(buyer::text,0));
 fresh:=public.quote_custom_package(item,buyer);
 IF jsonb_array_length(fresh->'owned_subject_ids')>0 THEN RAISE EXCEPTION 'Selected subjects are already owned'; END IF;
 IF (fresh->>'price')::numeric IS DISTINCT FROM (item->>'price')::numeric THEN RAISE EXCEPTION 'Pricing changed; refresh quote'; END IF;
 IF EXISTS(SELECT 1 FROM public.bkash_payments b CROSS JOIN LATERAL jsonb_array_elements(b.selected_packages) p
   WHERE b.user_id=buyer AND b.status='initiated' AND p->>'kind'='custom'
     AND EXISTS(SELECT 1 FROM jsonb_array_elements_text(p->'subject_ids') old_id
       JOIN jsonb_array_elements_text(item->'subject_ids') new_id ON old_id.value=new_id.value))
 THEN RAISE EXCEPTION 'An unfinished payment already includes these subjects. Finish or reconcile that payment first.'; END IF;
 IF (context->>'amount')::numeric<=0 OR (context->>'discount')::numeric<0
   OR (context->>'amount')::numeric+(context->>'discount')::numeric<>(fresh->>'price')::numeric THEN RAISE EXCEPTION 'Invalid payable amount'; END IF;
 INSERT INTO public.bkash_payments(user_id,merchant_invoice_number,amount,discount,coupon_code,selected_packages,payer_reference,institute_name,teacher_name,teacher_email,status,environment)
 VALUES(buyer,context->>'merchant_invoice_number',(context->>'amount')::numeric,(context->>'discount')::numeric,context->>'coupon_code',
   jsonb_build_array(fresh),context->>'payer_reference',context->>'institute_name',context->>'teacher_name',context->>'teacher_email','initiated',context->>'environment') RETURNING bkash_payments.id INTO id;
 RETURN id;
END $$;
REVOKE ALL ON FUNCTION public.reserve_custom_payment(jsonb) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.reserve_custom_payment(jsonb) TO service_role;

-- Custom entitlement activation and payment completion commit together, with a
-- payment-row lock making duplicate callbacks and reconciliation idempotent.
CREATE FUNCTION public.complete_custom_payment(payment_ref bigint,receipt jsonb) RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE b public.bkash_payments; item jsonb; sub_id bigint; existing_id bigint;
BEGIN
 SELECT * INTO b FROM public.bkash_payments WHERE id=payment_ref FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Payment missing'; END IF;
 IF receipt->>'transactionStatus' IS DISTINCT FROM 'Completed' OR nullif(receipt->>'trxID','') IS NULL
   OR (receipt->>'amount')::numeric IS DISTINCT FROM b.amount OR receipt->>'currency' IS DISTINCT FROM 'BDT'
   OR receipt->>'paymentID' IS DISTINCT FROM b.payment_id THEN RAISE EXCEPTION 'Payment verification mismatch'; END IF;
 SELECT subscription_id INTO existing_id FROM public.custom_package_purchases WHERE payment_id=b.id;
 IF FOUND THEN RETURN existing_id; END IF;
 IF jsonb_array_length(b.selected_packages)<>1 THEN RAISE EXCEPTION 'Invalid custom order'; END IF;
 item:=b.selected_packages->0;
 IF item->>'kind' IS DISTINCT FROM 'custom' OR (item->>'price')::numeric-b.discount<>b.amount THEN RAISE EXCEPTION 'Invalid custom order'; END IF;
 INSERT INTO public.subscriptions(teacher_id,plan,package_type,status,starts_at,ends_at,bkash_payment_id)
 VALUES(b.user_id,'Custom #'||b.id||' — '||(item->>'class_name')||' — '||(item->>'subject_name'),'custom','active',now(),now()+interval '365 days',b.id) RETURNING id INTO sub_id;
 INSERT INTO public.custom_package_purchases(user_id,subscription_id,payment_id,version,class_id,class_level,group_name,subject_ids,regular_total,package_price,coupon_discount,final_price,pricing_snapshot)
 VALUES(b.user_id,sub_id,b.id,item->>'version',(item->>'class_id')::bigint,item->>'class_level',item->>'group',
   ARRAY(SELECT value::bigint FROM jsonb_array_elements_text(item->'subject_ids')),(item->>'regular_total')::numeric,(item->>'price')::numeric,b.discount,b.amount,item);
 UPDATE public.bkash_payments SET status='completed',trx_id=receipt->>'trxID',bkash_response=receipt,error_message=NULL WHERE id=b.id;
 IF b.coupon_code IS NOT NULL THEN PERFORM public.increment_coupon_usage(b.coupon_code); END IF;
 RETURN sub_id;
END $$;
REVOKE ALL ON FUNCTION public.complete_custom_payment(bigint,jsonb) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.complete_custom_payment(bigint,jsonb) TO service_role;

-- Paper creation validates question IDs through the caller's question RLS.
-- Previously saved papers and teacher-owned/free questions remain unchanged.
CREATE FUNCTION public.validate_paper_question_access() RETURNS trigger
LANGUAGE plpgsql SET search_path=public AS $$
DECLARE expected integer; visible integer;
BEGIN
 IF auth.uid() IS NULL OR public.has_role(auth.uid(),'admin') THEN RETURN NEW; END IF;
 SELECT count(DISTINCT id) INTO expected FROM unnest(NEW.question_ids) id;
 SELECT count(*) INTO visible FROM public.questions WHERE id=ANY(NEW.question_ids);
 IF expected<>visible THEN RAISE EXCEPTION 'Paper contains inaccessible questions'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER saved_papers_validate_access BEFORE INSERT OR UPDATE OF question_ids ON public.saved_papers
FOR EACH ROW EXECUTE FUNCTION public.validate_paper_question_access();

